/**
 * G-TRACE (instructions.md §7). Parses requirement IDs from PRD.md and @req tags from tests.
 *
 *   npm run check:trace            -> checks P0/P1 reqs of completed milestones, writes docs/progress/TRACE.md
 *   npm run check:trace -- --all   -> final gate: every P0/P1 requirement, any milestone
 *   npm run check:trace -- --plan  -> checks every P0/P1 req is cited by a task card in instructions.md
 *
 * Completed milestones are listed in docs/progress/trace-scope.json: { "milestones": ["M0", "M1"] }.
 * Exemptions: docs/progress/TRACE-EXEMPT.md lines like "- LEG-001: verified by legal-pages.spec.ts".
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface Req {
  id: string;
  priority: "P0" | "P1" | "P2";
  milestone: string | null;
}

export function parsePrd(prd: string): Map<string, Req> {
  const reqs = new Map<string, Req>();
  const re = /\*\*([A-Z0-9]+-\d{3})(?:[^*]*?)\((P[012])(?:,\s*(M\d))?\)/g;
  for (const m of prd.matchAll(re)) {
    const id = m[1]!;
    if (!reqs.has(id))
      reqs.set(id, { id, priority: m[2] as Req["priority"], milestone: m[3] ?? null });
  }
  // table-defined requirements: "new: **SET-030**" rows, default P1 unless stated
  for (const line of prd.split("\n")) {
    for (const m of line.matchAll(/new: \*\*([A-Z0-9]+-\d{3})\*\*/g)) {
      const id = m[1]!;
      const priority = /\bP2\b/.test(line) ? "P2" : "P1";
      if (!reqs.has(id)) reqs.set(id, { id, priority, milestone: null });
    }
  }
  return reqs;
}

/** Expand "INP-001..009" style ranges and plain IDs in a text blob. */
export function citedIds(text: string): Set<string> {
  const out = new Set<string>(text.match(/\b[A-Z0-9]+-\d{3}\b/g) ?? []);
  for (const m of text.matchAll(/\b([A-Z0-9]+)-(\d{3})\.\.(\d{3})\b/g)) {
    for (let k = Number(m[2]); k <= Number(m[3]); k++)
      out.add(`${m[1]}-${String(k).padStart(3, "0")}`);
  }
  return out;
}

function walk(dir: string, out: string[] = []): string[] {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".next")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(test|spec)\.tsx?$/.test(p)) out.push(p);
  }
  return out;
}

export function collectTags(files: string[]): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const f of files) {
    const src = readFileSync(f, "utf8");
    for (const m of src.matchAll(/@req\s+([A-Z0-9]+-\d{3}(?:\.\.\d{3})?)/g)) {
      for (const id of citedIds(m[1]!)) {
        const list = map.get(id) ?? [];
        if (!list.includes(f)) list.push(f);
        map.set(id, list);
      }
    }
  }
  return map;
}

function main() {
  const prd = readFileSync("PRD.md", "utf8");
  const reqs = parsePrd(prd);
  const plan = process.argv.includes("--plan");

  if (plan) {
    const cited = citedIds(readFileSync("instructions.md", "utf8"));
    const missing = [...reqs.values()].filter((r) => r.priority !== "P2" && !cited.has(r.id));
    console.log(`PRD requirements: ${reqs.size}`);
    if (missing.length) {
      console.error("Not cited by any task card:", missing.map((r) => r.id).join(", "));
      process.exit(1);
    }
    console.log("plan coverage: all P0/P1 requirements are cited by task cards");
    return;
  }

  const scopePath = "docs/progress/trace-scope.json";
  const scope: string[] = existsSync(scopePath)
    ? JSON.parse(readFileSync(scopePath, "utf8")).milestones
    : [];
  const exemptPath = "docs/progress/TRACE-EXEMPT.md";
  const exempt = existsSync(exemptPath)
    ? citedIds(readFileSync(exemptPath, "utf8"))
    : new Set<string>();
  const tags = collectTags([...walk("src"), ...walk("tests"), ...walk("scripts")]);

  const all = process.argv.includes("--all");
  const inScope = [...reqs.values()].filter(
    (r) => r.priority !== "P2" && (all || (r.milestone !== null && scope.includes(r.milestone))),
  );
  const missing = inScope.filter((r) => !tags.has(r.id) && !exempt.has(r.id));

  const rows = [...reqs.values()]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((r) => {
      const t = tags.get(r.id);
      const status = t
        ? "✅"
        : exempt.has(r.id)
          ? "➖ exempt"
          : r.priority === "P2"
            ? "P2 (deferred)"
            : "—";
      return `| ${r.id} | ${r.priority} | ${r.milestone ?? ""} | ${status} | ${(t ?? []).slice(0, 3).join("<br>")} |`;
    });
  const traced = [...reqs.values()].filter((r) => tags.has(r.id) || exempt.has(r.id)).length;
  const md = [
    "# Requirement traceability (generated by `npm run check:trace`)",
    "",
    `Requirements: ${reqs.size} · traced or exempt: ${traced} · milestones in scope: ${scope.join(", ") || "none"}`,
    "",
    "| ID | Priority | Milestone | Status | Tests |",
    "|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
  writeFileSync("docs/progress/TRACE.md", md);
  console.log(
    `PRD requirements: ${reqs.size}; in scope (P0/P1 of ${scope.join(",") || "-"}): ${inScope.length}; traced/exempt overall: ${traced}`,
  );
  if (missing.length) {
    console.error("Untraced in-scope requirements:", missing.map((r) => r.id).join(", "));
    process.exit(1);
  }
  console.log("trace: OK");
}

if (process.argv[1]?.endsWith("trace.ts")) main();
