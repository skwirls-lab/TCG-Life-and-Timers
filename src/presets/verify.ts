function describeValue(c: CounterDefinition): string {
  const parts = [`start ${c.start}`];
  if (c.threshold) {
    const cmp = c.threshold.comparator === "<=" ? "≤" : "≥";
    parts.push(`${cmp} ${c.threshold.value} → ${c.threshold.outcome}`);
  }
  if (c.max !== undefined && c.max !== null) parts.push(`max ${c.max}`);
  return parts.join(", ");
}

/** Every value of a preset that still needs verification. */
export function presetVerifyItems(p: Preset): VerifyItem[] {
  const base = {
    presetId: p.id,
    presetName: p.name,
    game: p.game,
    ...(p.rulesUrl ? { rulesUrl: p.rulesUrl } : {}),
  };
  const items: VerifyItem[] = p.counters
    .filter((c) => c.verify)
    .map((c) => ({
      ...base,
      target: c.name,
      counterId: c.id,
      value: describeValue(c),
      check: COUNTER_CHECKS[c.id] ?? "Confirm this value against the official rules.",
    }));
  for (const x of PRESET_CHECKS[p.id] ?? []) items.push({ ...base, ...x });
  return items;
}

export function hasUnverifiedValues(p: Preset): boolean {
  return presetVerifyItems(p).length > 0;
}

function cell(s: string): string {
  return s.replaceAll("|", "\\|").replaceAll("\n", " ");
}

/** Markdown for docs/RULES-TO-VERIFY.md (shared counters are listed once with all presets). */
export function rulesToVerifyMarkdown(presets: readonly Preset[]): string {
  const rows = new Map<string, { item: VerifyItem; presets: string[] }>();
  for (const p of presets) {
    for (const item of presetVerifyItems(p)) {
      const key = [item.game, item.target, item.value, item.check].join("\u0000");
      const row = rows.get(key);
      if (row) row.presets.push(p.name + (p.hidden ? " (hidden)" : ""));
      else rows.set(key, { item, presets: [p.name + (p.hidden ? " (hidden)" : "")] });
    }
  }
  const lines = [
    "# Rules to verify",
    "",
    "Generated by `npx tsx scripts/gen-rules-to-verify.ts` from the built-in presets",
    "(`verify: true` counters and `src/presets/verify.ts`). Do not edit by hand.",
    "",
    "When a value is confirmed, fix the preset data if needed, drop its `verify` flag (or the",
    "entry in `PRESET_CHECKS`), and regenerate this file.",
    "",
    `Items: ${rows.size}`,
    "",
    "| Game | Preset(s) | Counter / setting | Current value | What to check | Rules |",
    "|---|---|---|---|---|---|",
  ];
  for (const { item, presets: names } of rows.values()) {
    const target = item.counterId ? `${item.target} (\`${item.counterId}\`)` : item.target;
    const url = item.rulesUrl ? `[rules](${item.rulesUrl})` : "—";
    lines.push(
      `| ${cell(item.game)} | ${cell(names.join(", "))} | ${cell(target)} | ${cell(item.value)} | ${cell(item.check)} | ${url} |`,
    );
  }
  lines.push(
    "",
    "## Official rules links",
    "",
    "The rules URLs could not be fetched from the build sandbox; confirm each link still points to",
    "the publisher's current rules page.",
    "",
  );
  const seenUrls = new Set<string>();
  const seenGames = new Set<string>();
  for (const p of presets) {
    if (!p.rulesUrl || seenUrls.has(p.rulesUrl)) continue;
    seenUrls.add(p.rulesUrl);
    const label = seenGames.has(p.game) ? `${p.game} (${p.name})` : p.game;
    seenGames.add(p.game);
    lines.push(`- ${label}: ${p.rulesUrl}`);
  }
  lines.push("");
  return lines.join("\n");
}
